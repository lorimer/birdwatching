#!/usr/bin/env python3
"""Generate Birdwatcher boot-screen assets for the T-Display-S3 (320x170).

Outputs (into --out, default ./out):
  bw_scene.png       152x152 scope view (pigeon-cam + flock), transparent outside circle
  bw_wordmark.png    140x98  "BIRD / WATCHER / Falco surveillus", transparent bg
  bw_scene_png.h     PROGMEM byte array of bw_scene.png   (for g->drawPng)
  bw_wordmark_png.h  PROGMEM byte array of bw_wordmark.png

Requires: Pillow, rsvg-convert (librsvg), Poppins Bold/LightItalic TTFs.
"""
import argparse, io, os, subprocess
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
SCENE_PX = 152
SS = 4  # supersample factor

FONT_BOLD = "/usr/share/fonts/truetype/google-fonts/Poppins-Bold.ttf"
FONT_ITAL = "/usr/share/fonts/truetype/google-fonts/Poppins-LightItalic.ttf"

WHITE = (243, 244, 246, 255)
AMBER = (251, 191, 36, 255)
GREY = (156, 163, 175, 255)


def render_scene(svg_path):
    png = subprocess.run(
        ["rsvg-convert", "-w", str(SCENE_PX * SS), "-h", str(SCENE_PX * SS), svg_path],
        check=True, capture_output=True).stdout
    im = Image.open(io.BytesIO(png)).convert("RGBA")
    return im.resize((SCENE_PX, SCENE_PX), Image.LANCZOS)


def fit_font(path, text, width, start):
    size = start
    while size > 6:
        f = ImageFont.truetype(path, size)
        if f.getbbox(text)[2] - f.getbbox(text)[0] <= width:
            return f
        size -= 1
    return ImageFont.truetype(path, size)


def render_wordmark(w=140, h=98):
    W, H = w * SS, h * SS
    im = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    f_big = fit_font(FONT_BOLD, "WATCHER", W, 60 * SS)
    f_bird = ImageFont.truetype(FONT_BOLD, f_big.size)
    f_tag = fit_font(FONT_ITAL, "Falco surveillus", W, 12 * SS)

    def draw_left(y, text, font, fill):
        bb = font.getbbox(text)
        d.text((-bb[0], y - bb[1]), text, font=font, fill=fill)
        return y + (bb[3] - bb[1])

    y = 0
    y = draw_left(y, "BIRD", f_bird, WHITE) + 7 * SS
    y = draw_left(y, "WATCHER", f_big, AMBER) + 8 * SS
    d.rectangle([0, y, W, y + 1 * SS - 1], fill=GREY)
    y += 6 * SS
    y = draw_left(y, "Falco surveillus", f_tag, GREY)
    im = im.crop((0, 0, W, min(H, y + 2 * SS)))
    return im.resize((im.width // SS, im.height // SS), Image.LANCZOS)


def to_header(png_path, name):
    data = open(png_path, "rb").read()
    w, h = Image.open(png_path).size
    lines = [f"// Generated by tools/gen_birdwatcher_assets.py from {os.path.basename(png_path)}",
             "#pragma once", "#include <stdint.h>", "#include <pgmspace.h>",
             f"static const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines += ["};", f"static const uint32_t {name}_len = {len(data)};",
              f"static const int {name}_W = {w};", f"static const int {name}_H = {h};", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--svg", default=os.path.join(HERE, "..", "art", "scene.svg"))
    ap.add_argument("--out", default="out")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)

    scene = render_scene(a.svg)
    wm = render_wordmark()
    for img, base, sym in ((scene, "bw_scene", "BW_SCENE_PNG"), (wm, "bw_wordmark", "BW_WORDMARK_PNG")):
        p = os.path.join(a.out, base + ".png")
        img.save(p, optimize=True)
        with open(os.path.join(a.out, base + "_png.h"), "w") as fh:
            fh.write(to_header(p, sym))
        print(f"{base}.png {img.size} {os.path.getsize(p)} bytes")


if __name__ == "__main__":
    main()
